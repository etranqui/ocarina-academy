// Runs after `next build`: writes out/sw.js with a precache list of every
// exported file, versioned by a hash of their contents. A new deploy changes
// the hash, so the browser installs the new worker and drops the old cache.
import { createHash } from "node:crypto";
import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";

const OUT = "out";
const SKIP = [/^sw\.js$/, /\.map$/, /^404\/?/, /^_not-found/];

async function walk(dir) {
  const files = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) files.push(...(await walk(p)));
    else files.push(p);
  }
  return files;
}

const hash = createHash("sha256");
const urls = [];
let bytes = 0;
for (const file of (await walk(OUT)).sort()) {
  const rel = relative(OUT, file).split(sep).join("/");
  if (SKIP.some((r) => r.test(rel))) continue;
  const buf = await readFile(file);
  hash.update(rel).update(buf);
  bytes += (await stat(file)).size;
  // Pages are requested by folder URL (trailingSlash), e.g. /library/ → library/index.html
  urls.push(rel === "index.html" ? "/" : rel.endsWith("/index.html") ? `/${rel.slice(0, -"index.html".length)}` : `/${rel}`);
}
const version = hash.digest("hex").slice(0, 12);

const sw = `// Generated by scripts/build-sw.mjs — do not edit.
const VERSION = ${JSON.stringify(version)};
const CACHE = "ocarina-academy-" + VERSION;
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("ocarina-academy-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  const url = new URL(req.url);
  if (req.method !== "GET" || url.origin !== self.location.origin) return;
  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE);
      // Pages: /songs/x → /songs/x/ ; RSC payloads carry a ?_rsc= query.
      const path = req.mode === "navigate" && !url.pathname.endsWith("/") && !url.pathname.includes(".") ? url.pathname + "/" : url.pathname;
      const hit = await cache.match(path, { ignoreSearch: true });
      if (hit) return hit;
      try {
        return await fetch(req);
      } catch (e) {
        if (req.mode === "navigate") return (await cache.match("/")) || Response.error();
        throw e;
      }
    })(),
  );
});
`;
await writeFile(join(OUT, "sw.js"), sw);
console.log(`sw.js: ${urls.length} files, ${(bytes / 1024 / 1024).toFixed(1)} MB, version ${version}`);
